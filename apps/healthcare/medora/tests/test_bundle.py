@dataclass
class TestResult:
    section: str
    name: str
    passed: bool
    skipped: bool = False
    message: str = ""

@dataclass
class TestSuite:
    results: List[TestResult] = field(default_factory=list)
    bail: bool = False
    json_output: bool = False
    _start_time: float = field(default_factory=time.time)

    def ok(self, section, name, msg=""):
        self.results.append(TestResult(section, name, True, False, msg))
        if not self.json_output:
            print(f"    \033[32m\u2713\033[0m {name}")

    def fail(self, section, name, msg=""):
        self.results.append(TestResult(section, name, False, False, msg))
        if not self.json_output:
            print(f"    \033[31m\u2717\033[0m {name}")
            if msg:
                for line in msg.splitlines()[:5]:
                    print(f"      {line}")
        if self.bail:
            self.print_summary()
            sys.exit(1)

    def skip(self, section, name, reason=""):
        self.results.append(TestResult(section, name, True, True, f"SKIPPED: {reason}"))
        if not self.json_output:
            print(f"    \033[33m\u25cb\033[0m {name} (skipped: {reason})")

    def print_summary(self):
        passed = sum(1 for r in self.results if r.passed and not r.skipped)
        failed = sum(1 for r in self.results if not r.passed)
        skipped = sum(1 for r in self.results if r.skipped)
        total = len(self.results)
        elapsed = time.time() - self._start_time

        if self.json_output:
            print(json.dumps({
                "passed": passed, "failed": failed, "skipped": skipped,
                "total": total, "elapsed_s": round(elapsed, 1),
                "tests": [
                    {"section": r.section, "name": r.name, "passed": r.passed,
                     "skipped": r.skipped, "message": r.message}
                    for r in self.results
                ],
            }, indent=2))
            return failed == 0

        # Per-section summary
        sections = {}
        for r in self.results:
            s = sections.setdefault(r.section, {"pass": 0, "fail": 0, "skip": 0})
            if r.skipped:
                s["skip"] += 1
            elif r.passed:
                s["pass"] += 1
            else:
                s["fail"] += 1

        print(f"\n{'='*60}")
        print(f"  Bundle Validation: {passed} passed, {failed} failed, {skipped} skipped ({elapsed:.1f}s)")
        print(f"  Total checks: {total}")
        print()
        for sec, counts in sections.items():
            status = "\033[32m\u2713\033[0m" if counts["fail"] == 0 else "\033[31m\u2717\033[0m"
            print(f"    {status} {sec}: {counts['pass']} passed"
                  + (f", {counts['fail']} failed" if counts["fail"] else "")
                  + (f", {counts['skip']} skipped" if counts["skip"] else ""))
        if failed:
            print(f"\n  Failures:")
            for r in self.results:
                if not r.passed:
                    print(f"    \033[31m\u2717\033[0m [{r.section}] {r.name}")
                    if r.message:
                        print(f"      {r.message[:120]}")
        print(f"{'='*60}")
        return failed == 0


