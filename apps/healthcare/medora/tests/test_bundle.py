#!/usr/bin/env python3
"""
test_bundle.py -- Pre-flight validation for Supero generated apps.

Validates app generation quality WITHOUT running ./run.sh or starting
the server. Zero external dependencies -- uses only Python stdlib.

Checks:
  1. Required files    -- all expected files exist and aren't empty/truncated
  2. .env config       -- required vars, auth, project name, port consistency
  3. Schema validation -- syntax, namespaces, enum refs, reference targets
  4. Config validation -- app_name, tenants, users, roles, env wiring
  5. Setup.py          -- syntax, required functions, seed field name accuracy
  6. config.js         -- domain, project, appNamespace, public schemas
  7. app.js            -- AppShell, render(), SUPERO_CONFIG wiring, tabs
  8. supero-ui.js      -- _qualifySchema, SuperoClient, size check
  9. run.sh            -- SDK version stamped, executable
 10. Dockerfile        -- FROM, COPY, CMD, no .env leak
 11. Documentation     -- README.md, CLAUDE.md, CUSTOMIZATION.md
 12. Public wiring     -- .env -> config.js -> app.js end-to-end
 13. Seed field match  -- seed_record field names vs schema attributes
 14. SDK versions      -- base SDK installed, version matches run.sh pin
 15. Post-install      -- API key, config.js project, backend records

Ships with the app bundle (generated by AI service).
Run BEFORE ./run.sh to catch generation errors early.
Run AFTER ./run.sh to validate post-install state.

Usage:
    python3 test_bundle.py                # full pre-flight validation
    python3 test_bundle.py --bail         # stop on first failure
    python3 test_bundle.py --json         # JSON output for CI
    python3 test_bundle.py --post-install # include backend record checks
"""

