    # .supero-run.log
    log = os.path.join(APP_DIR, ".supero-run.log")
    if os.path.exists(log):
        suite.ok("post-install", ".supero-run.log exists")
    else:
        suite.skip("post-install", "No .supero-run.log", "Setup may not have completed")

    # Backend record verification (optional -- needs server running)
    if not check_backend:
        suite.skip("post-install", "Backend record check",
                   "Use --post-install to verify records in DB")
        return

    if not API_KEY:
        suite.skip("post-install", "Backend check", "No API key")
        return

    _port = _env("PORT", _env("UI_PORT", "5648"))
