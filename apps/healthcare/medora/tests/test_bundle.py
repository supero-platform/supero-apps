def check_billing_wiring(suite):
    """[18] Billing Wiring — stripe_checkout service must be plumbed.

    Catches the three common MiniShop-class failure modes:

        (a) stripe_checkout is in config.services but no tab with
            schema='billing_invoice' or billingRole:'invoice' exists,
            AND no EVENT_BINDINGS override maps to a library billing
            workflow. The Pay with Stripe UI will never render.

        (b) WORKFLOW_DEFINITIONS redefines a library-provided billing
            workflow (billing_invoice_created, billing_payment_received)
            or a common PRD alias (order_created, checkout_started,
            payment_success, payment_failed). These must be bound via
            EVENT_BINDINGS, not redefined.

        (c) A tab has billingRole:'invoice' but the referenced schema
            lacks required fields (total_amount, customer_email,
            customer_name). The library workflow input_map can't
            resolve.

    Authoritative reference: docs/8.billing.md (renamed-schema contract).
    """
    if not suite.json_output:
        print("\n  [18] Billing Wiring\n")

    # ── Load source files ──
    config_path = os.path.join(APP_DIR, "config.py")
    app_js_path = os.path.join(APP_DIR, "ui", "app.js")
    setup_path  = os.path.join(APP_DIR, "setup.py")
    schemas_path = os.path.join(APP_DIR, "schemas.py")

    def _read(p):
        if not os.path.exists(p):
            return ""
        with open(p) as f:
            return f.read()

    config_py  = _read(config_path)
    app_js     = _read(app_js_path)
    setup_py   = _read(setup_path)
    schemas_py = _read(schemas_path)

    # ── Fast exit: no billing/stripe involvement at all ──
    stripe_in_config = ("stripe_checkout" in config_py
                        or "'stripe_checkout'" in config_py
                        or '"stripe_checkout"' in config_py)
    billing_in_config = ("'billing'" in config_py
                         or '"billing"' in config_py)

    if not (stripe_in_config or billing_in_config):
        suite.skip("billing-wiring", "Billing wiring check",
                   "No billing/stripe_checkout service — N/A")
        return

    # ──────────────────────────────────────────────────────────────
    # Check (a): stripe_checkout listed but nothing wires it
    # ──────────────────────────────────────────────────────────────
    if stripe_in_config:
        has_invoice_schema = ("schema: 'billing_invoice'" in app_js
                              or 'schema: "billing_invoice"' in app_js)
        has_billing_role   = ("billingRole: 'invoice'" in app_js
                              or 'billingRole: "invoice"' in app_js)
        has_library_binding = ("billing_invoice_created" in setup_py
                               or "billing_payment_received" in setup_py)

        if not (has_invoice_schema or has_billing_role or has_library_binding):
            suite.fail(
                "billing-wiring",
                "stripe_checkout has no billing path",
                "config.services includes 'stripe_checkout' but app.js has no\n"
                "tab with schema='billing_invoice' or billingRole:'invoice',\n"
                "and setup.py has no EVENT_BINDINGS pointing at\n"
                "billing_invoice_created or billing_payment_received.\n"
                "\n"
                "Fix: either (1) add billingRole:'invoice' to your order/invoice\n"
                "tab, OR (2) rename a schema to 'billing_invoice'. Then add\n"
                "an EVENT_BINDINGS entry mapping @create:<yourschema> →\n"
                "billing_invoice_created. See docs/8.billing.md §'The\n"
                "renamed-schema contract'."
            )
        else:
            paths = []
            if has_invoice_schema:   paths.append("billing_invoice schema")
            if has_billing_role:     paths.append("billingRole:'invoice' tab")
            if has_library_binding:  paths.append("library workflow binding")
            suite.ok("billing-wiring",
                     "stripe_checkout wired via: " + ", ".join(paths))

    # ──────────────────────────────────────────────────────────────
    # Check (b): app redefines library-provided billing workflows
    # ──────────────────────────────────────────────────────────────
    LIBRARY_WF_IDS = (
        "billing_invoice_created",
        "billing_payment_received",
        # PRD aliases the LLM commonly mistakenly redefines:
        "order_created", "checkout_started", "checkout_completed",
        "payment_success", "payment_failed",
        "invoice_created", "payment_received",
    )

    # Parse WORKFLOW_DEFINITIONS via AST, same pattern as check_workflow_config
    wf_defs = []
    try:
        import ast as _ast
        tree = _ast.parse(setup_py)
        for node in tree.body:
            if (isinstance(node, _ast.Assign)
                    and len(node.targets) == 1
                    and isinstance(node.targets[0], _ast.Name)
                    and node.targets[0].id == "WORKFLOW_DEFINITIONS"):
                try:
                    wf_defs = _ast.literal_eval(node.value)
                except (ValueError, SyntaxError):
                    wf_defs = []
                break
    except SyntaxError:
        wf_defs = []

    redefined = []
    for wf in wf_defs:
        if isinstance(wf, dict):
            wfid = wf.get("workflow_id")
            if wfid in LIBRARY_WF_IDS and wf.get("steps"):
                redefined.append(wfid)

    if redefined:
        suite.fail(
            "billing-wiring",
            f"WORKFLOW_DEFINITIONS redefines library workflows: {redefined}",
            "These workflows are provided by the library when 'billing' is in\n"
            "config.services. Redefining them causes duplicate registrations\n"
            "and maintenance drift. Remove them and use EVENT_BINDINGS to\n"
            "bind your schemas to 'billing_invoice_created' and\n"
            "'billing_payment_received'. See docs/8.billing.md §'PRD\n"
            "terminology → library workflow lookup'."
        )
    elif wf_defs:
        suite.ok("billing-wiring",
                 f"No library-workflow redefinitions in {len(wf_defs)} WORKFLOW_DEFINITIONS")

    # ──────────────────────────────────────────────────────────────
    # Check (c): billingRole:'invoice' without required schema fields
    # ──────────────────────────────────────────────────────────────
    billing_role_pat = re.compile(
        r"schema:\s*['\"]([a-z_]+)['\"][^{}]*?billingRole:\s*['\"]invoice['\"]",
        re.DOTALL
    )
    # Also match the reverse order (billingRole before schema)
    billing_role_pat_rev = re.compile(
        r"billingRole:\s*['\"]invoice['\"][^{}]*?schema:\s*['\"]([a-z_]+)['\"]",
        re.DOTALL
    )

    invoice_role_schemas = set()
    for m in billing_role_pat.finditer(app_js):
        invoice_role_schemas.add(m.group(1))
    for m in billing_role_pat_rev.finditer(app_js):
        invoice_role_schemas.add(m.group(1))

    for sname in invoice_role_schemas:
        # Required fields for the library workflow input_map per
        # 8.billing.md renamed-schema contract
        required = ("total_amount", "customer_email", "customer_name")
        combined = schemas_py + "\n" + app_js
        # We check combined because attrs can also be declared inline
        # in app.js tabs.
        missing = [f for f in required if f not in combined]
        if missing:
            suite.fail(
                "billing-wiring",
                f"billingRole:'invoice' schema '{sname}' missing fields: {missing}",
                f"The InvoicePayPanel and library workflow input_map depend\n"
                f"on {list(required)}. Add the missing fields to the schema\n"
                f"definition in schemas.py. See docs/8.billing.md §'The\n"
                f"renamed-schema contract' step 2."
            )
        else:
            suite.ok("billing-wiring",
                     f"billingRole:'invoice' schema '{sname}' has required fields")

    if not invoice_role_schemas and billing_in_config:
        # billing service is on but no invoice role tab — only warn if
        # there's no billing_invoice tab either (covered by check a).
        pass

def main():
    parser = argparse.ArgumentParser(
        description="Pre-flight validation for Supero apps",
        formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bail", action="store_true", help="Stop on first failure")
    parser.add_argument("--json", action="store_true", help="JSON output for CI")
    parser.add_argument("--post-install", action="store_true",
                        help="Include backend record verification (needs server running)")
    args = parser.parse_args()

    if not DOMAIN:
        print("  x SUPERO_DOMAIN not set -- check .env")
        sys.exit(1)

    suite = TestSuite(bail=args.bail, json_output=args.json)

    _is_pre_install = not HAS_VENV

    if not args.json:
        print(f"\n{'='*60}")
        print(f"  Bundle Validation -- {cfg.app_name}")
        print(f"  Domain: {DOMAIN} | Project: {PROJECT}")
        print(f"  Schemas: {len(OBJECT_SCHEMAS)} objects, {len(ENUM_SCHEMAS)} enums")
        print(f"  Public: {', '.join(PUBLIC_SCHEMAS) or '(none)'}")
        if _is_pre_install:
            print(f"\n  Mode: PRE-FLIGHT (no .venv found)")
            print(f"  Only validating AI-generated files.")
            print(f"  Files created by ./run.sh will be skipped.")
        else:
            print(f"\n  Mode: POST-INSTALL (.venv found)")
        print(f"{'='*60}")

    check_required_files(suite)
    check_env(suite)
    check_schemas(suite)
    check_tab_schema_references(suite)
    check_config(suite)
    check_setup_py(suite)
    check_config_js(suite)
    check_app_js(suite)
    check_supero_ui_js(suite)
    check_run_sh(suite)
    check_dockerfile(suite)
    check_docs(suite)
    check_public_wiring(suite)
    check_sdk_versions(suite)
    check_workflow_config(suite)
    check_billing_wiring(suite)
    check_post_install(suite, check_backend=args.post_install)

    all_passed = suite.print_summary()

    if not args.json and _is_pre_install:
        print(f"\n  Next steps:")
        print(f"    1. ./run.sh                    Install SDK, bootstrap, seed data, start server")
        print(f"    2. ./run.sh --verify            Post-install validation (all checks)")
        print(f"    3. ./run.sh --e2e               Runtime e2e tests (server must be running)")
        print()

    sys.exit(0 if all_passed else 1)


if __name__ == "__main__":
    main()
