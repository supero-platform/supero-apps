# ---------------------------------------------------------------
# [17] Tab Schema References — app.js tabs[].schema must match
# a registered schema in schemas.py.
# ---------------------------------------------------------------
#
# Catches the most common LLM generation bug: `tab.schema` values
# that don't match any registered schema name. Typical failures:
#
#   schemas.py:  {"name": "FormDefinition"}   → stored as form_definition
#   app.js:      schema: 'formdefinition'      → 404 at runtime
#
# This check parses every `schema: 'xxx'` occurrence in app.js and
# cross-references it against the ALL_SCHEMAS table. Mismatches fail
# the bundle with a suggestion of the correct name (when we can
# guess it via normalized-name comparison).
#
# Add this function anywhere near check_app_js in test_bundle.py,
# then wire it in main() right after check_workflow_config (or wherever
# check ordering feels natural).

def check_tab_schema_references(suite):
    """[17] Tab Schema References — app.js tabs match schemas.py."""
    if not suite.json_output:
        print("\n  [17] Tab Schema References\n")

    path = os.path.join(APP_DIR, "ui", "app.js")
    if not os.path.exists(path):
        suite.skip("tab-schemas", "Tab schema check",
                   "app.js not found (already reported in [8])")
        return

    if not OBJECT_SCHEMAS:
        suite.skip("tab-schemas", "Tab schema check",
                   "No object schemas in schemas.py")
        return

    with open(path) as f:
        appjs = f.read()

    # ── Build the set of registered schema names in canonical snake_case ──
    #
    # Match the tabs[].schema values against multiple valid forms:
    #   - canonical snake:            "form_definition"
    #   - namespace-qualified:        "your_namespace:form_definition"
    #   - original PascalCase:        "FormDefinition"
    #
    # A tab schema value is valid if it matches ANY of these forms for
    # ANY registered schema.
    registered = []  # [(canonical_snake, original_name), ...]
    for s in OBJECT_SCHEMAS:
        original = s.get("name", "")
        if not original:
            continue
        registered.append((_to_snake(original), original))

    canonical_snake_set = {c for c, _ in registered}
    original_name_set = {o for _, o in registered}

    # ── Parse tabs[].schema values from app.js ──
    #
    # Matches patterns like:
    #   schema: 'form_definition'
    #   schema: "FormDefinition"
    #   schema:'formdefinition'
    # while capturing the line number for error messages.
    schema_refs = []  # [(line_no, value, tab_id_or_None), ...]

    # Split into lines so we can report line numbers
    lines = appjs.splitlines()

    # Track the most recent `id: '...'` so we can associate a `schema:`
    # with its containing tab. Not perfect (nested objects break it) but
    # good enough for the 95% case and only used for error-message hints.
    #
    # Regex shape notes:
    #   - `(?:^|[,{\s])` requires the `schema:` to be at start-of-line
    #     (modulo whitespace) or preceded by a comma/brace. This filters
    #     out matches inside prose strings like "description of schema:".
    #   - We also skip lines whose stripped form starts with `//` or `*`
    #     (common comment markers). This isn't a full JS parser but
    #     catches the realistic false-positive cases.
    recent_id = None
    id_re = re.compile(r"""(?:^|[,{\s])id:\s*['"]([^'"]+)['"]""")
    schema_re = re.compile(r"""(?:^|[,{\s])schema:\s*['"]([^'"]+)['"]""")

    for i, line in enumerate(lines, start=1):
        stripped = line.lstrip()
        # Skip line-comments and block-comment continuation lines.
        # (Block comments that span multiple lines and include the word
        # "schema:" inside are rare enough we don't handle them.)
        if stripped.startswith("//") or stripped.startswith("*"):
            continue

        id_match = id_re.search(line)
        if id_match:
            recent_id = id_match.group(1)

        schema_match = schema_re.search(line)
        if schema_match:
            schema_refs.append((i, schema_match.group(1), recent_id))

    if not schema_refs:
        suite.skip("tab-schemas", "Tab schema check",
                   "No schema: '...' declarations found in app.js")
        return

    suite.ok("tab-schemas",
             f"Found {len(schema_refs)} schema reference(s) in app.js")

    # ── Validate each reference ──
    def _strip_namespace(value):
        """`ns:schema` → `schema`; `schema` → `schema`."""
        return value.split(":", 1)[1] if ":" in value else value

    def _suggest_correction(bad_value):
        """Given a broken schema value, find the best match in registered.

        Strategy: normalize the bad value the same way we normalize
        registered names, then look for an exact match. If that fails,
        try substring matching. Returns the suggested canonical name
        or None.
        """
        bad_bare = _strip_namespace(bad_value).lower()
        bad_normalized = _to_snake(_strip_namespace(bad_value))

        # Exact normalized match (handles PascalCase passed as-is)
        if bad_normalized in canonical_snake_set:
            return bad_normalized

        # "formdefinition" has no underscores → try matching against
        # registered names with underscores stripped. If unique, that's
        # almost certainly what the LLM meant.
        stripped_registered = {
            canonical.replace("_", ""): canonical
            for canonical, _ in registered
        }
        if bad_bare in stripped_registered:
            return stripped_registered[bad_bare]

        # Substring fallback: does any registered canonical CONTAIN the
        # bad value (or vice versa)? Only suggest if unambiguous.
        substring_matches = [
            canonical for canonical in canonical_snake_set
            if bad_bare in canonical.replace("_", "")
               or canonical.replace("_", "") in bad_bare
        ]
        if len(substring_matches) == 1:
            return substring_matches[0]

        return None

    failures = 0
    orphan_refs = []  # references to schemas we couldn't correct

    for line_no, value, tab_id in schema_refs:
        bare = _strip_namespace(value)

        # Valid if any of these match
        is_valid = (
            bare in canonical_snake_set       # already canonical snake
            or bare in original_name_set      # original PascalCase / unchanged
            or _to_snake(bare) in canonical_snake_set  # PascalCase being fine
        )

        if is_valid:
            tab_hint = f" (tab '{tab_id}')" if tab_id else ""
            suite.ok("tab-schemas",
                     f"line {line_no}{tab_hint}: schema '{value}' ✓")
            continue

        # Invalid — try to suggest a fix
        failures += 1
        suggestion = _suggest_correction(value)
        tab_hint = f" (tab '{tab_id}')" if tab_id else ""

        if suggestion:
            msg = (
                f"line {line_no}{tab_hint}: schema '{value}' does NOT match "
                f"any registered schema. Did you mean '{suggestion}'? "
                f"Fix: edit ui/app.js line {line_no} to use "
                f"schema: '{suggestion}'"
            )
        else:
            msg = (
                f"line {line_no}{tab_hint}: schema '{value}' does NOT match "
                f"any registered schema, and no close match found. "
                f"Registered: {', '.join(sorted(canonical_snake_set)[:8])}"
                + ("..." if len(canonical_snake_set) > 8 else "")
            )
            orphan_refs.append(value)
        suite.fail("tab-schemas", f"Invalid schema reference '{value}'", msg)

    # ── Summary note about orphans (registered-but-unreferenced schemas) ──
    #
    # Collect the set of bare schema names actually referenced by tabs.
    # Any object schema not in that set is "orphaned" from the UI —
    # often fine (backend-only schemas, join tables), so we SKIP
    # rather than fail. Just informational.
    referenced_bare = set()
    for _, value, _ in schema_refs:
        bare = _strip_namespace(value)
        if bare in canonical_snake_set:
            referenced_bare.add(bare)
        elif _to_snake(bare) in canonical_snake_set:
            referenced_bare.add(_to_snake(bare))

    orphaned = canonical_snake_set - referenced_bare
    if orphaned:
        suite.skip(
            "tab-schemas",
            f"{len(orphaned)} schema(s) not referenced by any tab",
            f"Orphans (may be intentional): "
            f"{', '.join(sorted(orphaned)[:5])}"
            + ("..." if len(orphaned) > 5 else "")
        )

    if failures == 0:
        suite.ok("tab-schemas",
                 f"All {len(schema_refs)} schema reference(s) valid")


def check_workflow_config(suite):
    """[16] Workflow Config — EVENT_BINDINGS ↔ WORKFLOW_DEFINITIONS."""
    if not suite.json_output:
        print("\n  [16] Workflow Config\n")

    setup_path = os.path.join(APP_DIR, "setup.py")
    if not os.path.exists(setup_path):
        suite.skip("workflow-config", "Workflow config check", "No setup.py")
        return

    with open(setup_path) as f:
        setup_src = f.read()

    try:
        setup_tree = ast.parse(setup_src)
    except SyntaxError:
        suite.skip("workflow-config", "Workflow config check",
                   "setup.py has syntax error (already reported)")
        return

    def _extract_literal(tree, var_name):
        for node in tree.body:
            if (isinstance(node, ast.Assign)
                    and len(node.targets) == 1
                    and isinstance(node.targets[0], ast.Name)
                    and node.targets[0].id == var_name):
                try:
                    return ast.literal_eval(node.value)
                except (ValueError, SyntaxError):
                    return None
        return None

    wf_defs = _extract_literal(setup_tree, "WORKFLOW_DEFINITIONS") or []
    bindings = _extract_literal(setup_tree, "EVENT_BINDINGS") or []

    if not wf_defs and not bindings:
        suite.skip("workflow-config", "Workflow config check",
                   "No workflows (OK if app has no workflow features)")
        return

    # Build workflow_id → input_schema lookup
    workflow_ids = set()
    wf_input_schemas = {}
    wf_required_inputs = {}
    for wf in wf_defs:
        if not isinstance(wf, dict):
            continue
        wid = wf.get("workflow_id")
        if not wid:
            continue
        workflow_ids.add(wid)
        schema = wf.get("input_schema") or {}
        if isinstance(schema, dict):
            wf_input_schemas[wid] = set(schema.keys())
            wf_required_inputs[wid] = {
                k for k, v in schema.items()
                if isinstance(v, dict) and v.get("required")
            }

    # Schema names from ALL_SCHEMAS (loaded at module top)
    schema_names_all = {s.get("name") for s in ALL_SCHEMAS}
    schema_names_snake = {_to_snake(s.get("name", "")) for s in ALL_SCHEMAS}
    schema_names = schema_names_all | schema_names_snake

    # Allowed singular suffixes (don't false-positive on plural heuristic)
    _singular_ok = ("ss", "us", "is", "os", "ics", "news")

    def _is_probably_plural(schema_part):
        return (len(schema_part) > 3
                and schema_part.endswith("s")
                and not schema_part.endswith(_singular_ok))

    import re as _re
    def _validate_event(event):
        """Return (error_msg, schema_name_or_None). None error = valid."""
        if not isinstance(event, str) or not event.startswith("@"):
            return ("event must start with '@'", None)
        if event == "@signup":
            return (None, None)
        m = _re.match(r"^@([a-z]+):([a-zA-Z][a-zA-Z0-9_:]*)$", event)
        if not m:
            return ("event must be '@<verb>:<schema>'", None)
        verb, schema_part = m.group(1), m.group(2)
        if verb not in ("create", "update", "delete"):
            return ("unknown verb '{}' (use create/update/delete)".format(verb), None)
        if ":" in schema_part:
            return ("schema must be UNQUALIFIED (got '{}')".format(schema_part), None)
        if any(c.isupper() for c in schema_part):
            return ("schema must be snake_case (got '{}')".format(schema_part),
                    schema_part)
        if _is_probably_plural(schema_part):
            return ("schema name looks plural ('{}')".format(schema_part),
                    schema_part)
        return (None, schema_part)

    def _validate_path(path):
        if not isinstance(path, str):
            return "not a string"
        if "{{" in path or "}}" in path:
            return "contains '{{}}' templating — use plain dotted path"
        if path.startswith("$"):
            return "starts with '$' (JSONPath) — use plain dotted path"
        if path.startswith(("record.", "payload.", "data.")):
            return "redundant prefix '{}' — CRUD record IS the payload".format(
                path.split(".")[0])
        if not _re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*(\.[a-zA-Z_][a-zA-Z0-9_]*)*$",
                         path):
            return "doesn't look like a valid dotted path"
        return None

    # ── Summary counts ──────────────────────────────────────────────
    if wf_defs:
        suite.ok("workflow-config",
                 "Found {} WORKFLOW_DEFINITIONS, {} EVENT_BINDINGS".format(
                     len(wf_defs), len(bindings)))

    # ── Check 1: bindings well-formed ───────────────────────────────
    bad_events_seen = set()
    seen_events = set()
    for i, b in enumerate(bindings):
        ctx = "EVENT_BINDINGS[{}]".format(i)
        if not isinstance(b, dict):
            suite.fail("workflow-config", "{} not a dict".format(ctx))
            continue
        event = b.get("event")
        wf_id = b.get("workflow_id")
        input_map = b.get("input_map") or {}

        if not event:
            suite.fail("workflow-config", "{} missing 'event'".format(ctx))
            continue
        if not wf_id:
            suite.fail("workflow-config",
                       "{} (event={!r}) missing 'workflow_id'".format(ctx, event))
            continue

        ctx_e = "EVENT_BINDINGS[{!r}]".format(event)

        # Check 4+5: event format
        err, schema_part = _validate_event(event)
        if err:
            suite.fail("workflow-config", "{} {}".format(ctx_e, err))
            bad_events_seen.add(event)
        else:
            # Check 6: schema exists
            if schema_part and schema_part not in schema_names:
                suite.fail("workflow-config",
                           "{} schema '{}' not in ALL_SCHEMAS".format(
                               ctx_e, schema_part),
                           "Valid: " + ", ".join(sorted(schema_names_snake)[:6]))
            else:
                suite.ok("workflow-config",
                         "{} event format + schema OK".format(ctx_e))

        # Duplicate events
        if event in seen_events:
            suite.fail("workflow-config",
                       "{} duplicate event — only first fires".format(ctx_e))
        seen_events.add(event)

        # Check 3: workflow_id exists
        if wf_id not in workflow_ids:
            suite.fail("workflow-config",
                       "{} workflow_id={!r} has no matching definition".format(
                           ctx_e, wf_id),
                       "Available: " + ", ".join(sorted(workflow_ids)) if workflow_ids
                       else "No WORKFLOW_DEFINITIONS found")
        else:
            # Check 7: input_map keys
            if isinstance(input_map, dict) and wf_id in wf_input_schemas:
                expected = wf_input_schemas[wf_id]
                if expected:
                    unknown = set(input_map.keys()) - expected
                    if unknown:
                        suite.fail("workflow-config",
                                   "{} input_map keys not in workflow input_schema: {}".format(
                                       ctx_e, sorted(unknown)),
                                   "These will be SILENTLY IGNORED. "
                                   "Expected: " + ", ".join(sorted(expected)))
                    missing_req = wf_required_inputs.get(wf_id, set()) - set(input_map.keys())
                    if missing_req:
                        suite.fail("workflow-config",
                                   "{} input_map missing required keys: {}".format(
                                       ctx_e, sorted(missing_req)))

        # Check 8: input_map values are plain paths
        if isinstance(input_map, dict):
            for k, v in input_map.items():
                perr = _validate_path(v)
                if perr:
                    suite.fail("workflow-config",
                               "{} input_map[{!r}]={!r}: {}".format(
                                   ctx_e, k, v, perr))

    # ── Check 9: call order ─────────────────────────────────────────
    if "ensure_event_bindings" in setup_src:
        if "ensure_workflows" not in setup_src:
            suite.fail("workflow-config",
                       "ensure_event_bindings() called without ensure_workflows()",
                       "Register workflow definitions FIRST.")
        else:
            wf_pos = setup_src.find("ensure_workflows(")
            eb_pos = setup_src.find("ensure_event_bindings(")
            if wf_pos > 0 and eb_pos > 0 and eb_pos < wf_pos:
                suite.fail("workflow-config",
                           "ensure_event_bindings() called BEFORE ensure_workflows()",
                           "Bindings reference workflow_ids — swap the order.")
            else:
                suite.ok("workflow-config",
                         "ensure_workflows → ensure_event_bindings order correct")

    # ── Check 10: past-tense workflows without bindings ──────────────
    bound_wf_ids = {b.get("workflow_id") for b in bindings if isinstance(b, dict)}
    def _past_tense(name):
        if not name or "_" not in name:
            return False
        last = name.rsplit("_", 1)[-1]
        return (last.endswith("ed")
                or last in ("completed", "failed", "processed",
                            "received", "sent", "raised"))

    past_tense_unbound = [
        wf.get("workflow_id") for wf in wf_defs
        if isinstance(wf, dict)
        and wf.get("workflow_id")
        and _past_tense(wf["workflow_id"])
        and wf["workflow_id"] not in bound_wf_ids
    ]
    if past_tense_unbound:
        suite.fail("workflow-config",
                   "Past-tense workflows without EVENT_BINDING: {}".format(
                       past_tense_unbound),
                   "These names imply auto-triggers. Add bindings or confirm "
                   "they are admin-only (UI button via WORKFLOW_MAP).")

    # ── Final state ─────────────────────────────────────────────────
    if not bindings and wf_defs:
        # If we already warned about past-tense, don't double-warn
        if not past_tense_unbound:
            suite.skip("workflow-config",
                       "No EVENT_BINDINGS",
                       "All workflows admin-only (UI button only)")


